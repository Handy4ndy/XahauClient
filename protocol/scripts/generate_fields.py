#!/usr/bin/env python3
"""Freeze field registry -> protocol/data + src/Xahau/generated/protocol_fields.h

Usage:
  python protocol/scripts/generate_fields.py [path/to/field_registry.json]

Default source: existing protocol/data/field_registry.json in this repository.
Optional override: pass an external registry JSON path as argv[1].
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "protocol" / "data"
HDR = ROOT / "src" / "Xahau" / "generated" / "protocol_fields.h"

DEFAULT_SOURCES = [
    DATA / "field_registry.json",
]


def load_fields(src: Path) -> list[dict]:
    raw = json.loads(src.read_text(encoding="utf-8"))
    if isinstance(raw, dict) and "fields" in raw:
        items = raw["fields"]
    else:
        items = raw
    slim = []
    for f in items:
        name = f.get("name") or f.get("field")
        if not name:
            continue
        slim.append(
            {
                "name": name,
                "typeCode": int(f.get("typeCode") or 0),
                "nth": int(f.get("nth") or 0),
                "fieldCode": int(f.get("fieldCode") or ((int(f.get("typeCode") or 0) << 16) | int(f.get("nth") or 0))),
                "typeName": f.get("typeName") or f.get("typeSuffix") or "",
                "isVLEncoded": bool(f.get("isVLEncoded", False)),
                "isSigningField": bool(f.get("isSigningField", True)),
            }
        )
    return slim


def write_header(fields: list[dict]) -> None:
    HDR.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// AUTO-GENERATED by protocol/scripts/generate_fields.py — do not edit",
        "#pragma once",
        "#include <stdint.h>",
        "#include <string.h>",
        "namespace xahau { namespace protocol {",
        "struct FieldDef { const char* name; uint16_t typeCode; uint16_t nth; uint32_t fieldCode; };",
        "static const FieldDef kFields[] = {",
    ]
    for f in fields:
        name = f["name"].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(
            f'  {{"{name}", {f["typeCode"]}, {f["nth"]}, {f["fieldCode"]}u}},'
        )
    lines += [
        "};",
        "static const unsigned kFieldCount = sizeof(kFields) / sizeof(kFields[0]);",
        "inline const FieldDef* findField(const char* name) {",
        "  if (!name) return nullptr;",
        "  for (unsigned i = 0; i < kFieldCount; ++i) {",
        "    if (strcmp(kFields[i].name, name) == 0) return &kFields[i];",
        "  }",
        "  return nullptr;",
        "}",
        "}}  // namespace xahau::protocol",
        "",
    ]
    HDR.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    if src is None:
        for c in DEFAULT_SOURCES:
            if c.is_file():
                src = c
                break
    if src is None or not src.is_file():
        print("No field_registry.json source found", file=sys.stderr)
        return 1
    fields = load_fields(src)
    DATA.mkdir(parents=True, exist_ok=True)
    out_json = DATA / "field_registry.json"
    out_json.write_text(
        json.dumps(
            {
                "generated": datetime.now(timezone.utc).isoformat(),
                "source": str(src),
                "fields": fields,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    write_header(fields)
    print(f"fields={len(fields)} json={out_json} header={HDR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
